//! winit 物理键 → PC Set-1 扫描码（Windows SendInput 使用的那一套）。

use winit::keyboard::KeyCode;

/// 返回 (扫描码, 是否带 E0 扩展前缀)。
pub fn to_scancode(key: KeyCode, cmd_as_ctrl: bool) -> Option<(u16, bool)> {
    use KeyCode::*;
    let plain = |c: u16| Some((c, false));
    let ext = |c: u16| Some((c, true));
    match key {
        Escape => plain(0x01),
        Digit1 => plain(0x02),
        Digit2 => plain(0x03),
        Digit3 => plain(0x04),
        Digit4 => plain(0x05),
        Digit5 => plain(0x06),
        Digit6 => plain(0x07),
        Digit7 => plain(0x08),
        Digit8 => plain(0x09),
        Digit9 => plain(0x0a),
        Digit0 => plain(0x0b),
        Minus => plain(0x0c),
        Equal => plain(0x0d),
        Backspace => plain(0x0e),
        Tab => plain(0x0f),
        KeyQ => plain(0x10),
        KeyW => plain(0x11),
        KeyE => plain(0x12),
        KeyR => plain(0x13),
        KeyT => plain(0x14),
        KeyY => plain(0x15),
        KeyU => plain(0x16),
        KeyI => plain(0x17),
        KeyO => plain(0x18),
        KeyP => plain(0x19),
        BracketLeft => plain(0x1a),
        BracketRight => plain(0x1b),
        Enter => plain(0x1c),
        ControlLeft if cmd_as_ctrl && cfg!(windows) => ext(0x5b),
        ControlLeft => plain(0x1d),
        KeyA => plain(0x1e),
        KeyS => plain(0x1f),
        KeyD => plain(0x20),
        KeyF => plain(0x21),
        KeyG => plain(0x22),
        KeyH => plain(0x23),
        KeyJ => plain(0x24),
        KeyK => plain(0x25),
        KeyL => plain(0x26),
        Semicolon => plain(0x27),
        Quote => plain(0x28),
        Backquote => plain(0x29),
        ShiftLeft => plain(0x2a),
        Backslash => plain(0x2b),
        KeyZ => plain(0x2c),
        KeyX => plain(0x2d),
        KeyC => plain(0x2e),
        KeyV => plain(0x2f),
        KeyB => plain(0x30),
        KeyN => plain(0x31),
        KeyM => plain(0x32),
        Comma => plain(0x33),
        Period => plain(0x34),
        Slash => plain(0x35),
        ShiftRight => plain(0x36),
        NumpadMultiply => plain(0x37),
        AltLeft => plain(0x38),
        Space => plain(0x39),
        CapsLock => plain(0x3a),
        F1 => plain(0x3b),
        F2 => plain(0x3c),
        F3 => plain(0x3d),
        F4 => plain(0x3e),
        F5 => plain(0x3f),
        F6 => plain(0x40),
        F7 => plain(0x41),
        F8 => plain(0x42),
        F9 => plain(0x43),
        F10 => plain(0x44),
        NumLock => plain(0x45),
        ScrollLock => plain(0x46),
        Numpad7 => plain(0x47),
        Numpad8 => plain(0x48),
        Numpad9 => plain(0x49),
        NumpadSubtract => plain(0x4a),
        Numpad4 => plain(0x4b),
        Numpad5 => plain(0x4c),
        Numpad6 => plain(0x4d),
        NumpadAdd => plain(0x4e),
        Numpad1 => plain(0x4f),
        Numpad2 => plain(0x50),
        Numpad3 => plain(0x51),
        Numpad0 => plain(0x52),
        NumpadDecimal => plain(0x53),
        IntlBackslash => plain(0x56),
        F11 => plain(0x57),
        F12 => plain(0x58),
        NumpadEqual => plain(0x59),
        F13 => plain(0x64),
        F14 => plain(0x65),
        F15 => plain(0x66),

        NumpadEnter => ext(0x1c),
        ControlRight if cmd_as_ctrl && cfg!(windows) => ext(0x5c),
        ControlRight => ext(0x1d),
        NumpadDivide => ext(0x35),
        PrintScreen => ext(0x37),
        AltRight => ext(0x38),
        Home => ext(0x47),
        ArrowUp => ext(0x48),
        PageUp => ext(0x49),
        ArrowLeft => ext(0x4b),
        ArrowRight => ext(0x4d),
        End => ext(0x4f),
        ArrowDown => ext(0x50),
        PageDown => ext(0x51),
        Insert => ext(0x52),
        Delete => ext(0x53),
        ContextMenu => ext(0x5d),

        // 修饰键按对方系统的习惯互换（cmd_as_ctrl）：
        // Mac 上 Command → Ctrl（⌘C 即 Ctrl+C）；Windows 上 Ctrl → Win 键，被控的 Mac 收到的就是 Command。
        SuperLeft if cmd_as_ctrl => plain(0x1d),
        SuperRight if cmd_as_ctrl => ext(0x1d),
        SuperLeft => ext(0x5b),
        SuperRight => ext(0x5c),
        _ => None,
    }
}
